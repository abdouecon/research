# schedules figure from DRC_visualization_4.tex
src=open('../tables/DRC_visualization_4.tex').read()
sched={}
for line in src.split('\n'):
    if line.lstrip().startswith('%'): continue
    m=re.match(r'^\((\w+)\)\s*&\s*(.*?)\s*&(.*)\\\\',line.strip())
    if not m: continue
    vals=re.findall(r'\\gradient\{([\d.]+)\}',m.group(3))
    sched[m.group(1)]=[float(v) for v in vals]
json.dump(sched,open('tools/schedules.json','w'),indent=1)
ages=list(range(62,71))
def series(code): return ' '.join(f'({a},{v:g})' for a,v in zip(ages,sched[code]))
def panel(title, specs, ylab=True):
    L=[r'\begin{tikzpicture}',r'\begin{axis}[width=0.47\textwidth,height=0.40\textwidth,xmin=62,xmax=70,ymin=50,ymax=180,',
       r'  xtick={62,...,70},ytick={60,80,100,120,140,160,180},',
       r'  title={'+title+r'},title style={font=\small},',
       r'  xlabel={Claiming age},'+(r'ylabel={Benefit (\% of PIA)},' if ylab else ''),
       r'  grid=both,grid style={line width=.1pt, draw=gray!15},major grid style={line width=.2pt,draw=gray!30},',
       r'  tick label style={font=\scriptsize},label style={font=\footnotesize},',
       r'  legend style={font=\tiny,at={(0.02,0.98)},anchor=north west,draw=gray!50,fill=white,fill opacity=0.9,text opacity=1},legend cell align=left]']
    for code,lab,style in specs:
        L.append(rf'\addplot[{style}] coordinates {{{series(code)}}};')
        L.append(rf'\addlegendentry{{{lab}}}')
    L+= [r'\draw[gray!60,densely dotted] (axis cs:62,100) -- (axis cs:70,100);',r'\end{axis}',r'\end{tikzpicture}']
    return '\n'.join(L)
