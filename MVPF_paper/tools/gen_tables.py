import re, os, sys, json
sys.path.insert(0, os.path.dirname(__file__))
from parse_tables import parse
OUT='./tables/'
os.makedirs(OUT, exist_ok=True)

def num(s):
    s=s.strip()
    # Pad entries printed with one decimal in the source (trailing zero dropped, e.g. 0.3, 3.6) to the
    # two decimals of their columns. Formatting only: K3's 3.6 is D3's 3.60 in welfare_decomposition_gradient.tex.
    if re.fullmatch(r'-?\d+\.\d', s): s=s+'0'
    if s.startswith('-'): return '$-$'+s[1:]
    return s
def mvpf(s):
    s=s.strip()
    if s in ('$\\infty$',): return '$\\infty$'
    if s.startswith('$['): return s.replace('+\\infty',' +\\infty').replace(',',',\\,')
    return s

HEAD = r"""\begin{tabular}{@{}l l c c c c c c c c@{}}
\toprule
 & & \multicolumn{2}{c}{Welfare} & \multicolumn{3}{c}{Fiscal cost (\% change)} & \multicolumn{3}{c}{$\Delta$ Participation (pp)} \\
\cmidrule(lr){3-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}
 & Reform & MVPF & WTP (\%) & Net & Direct & Indirect & 30--49 & 62--64 & 65--69 \\
\midrule
"""
FOOT = r"""\bottomrule
\end{tabular}
"""
def rowtex(r, label=None):
    code=r[0]; lab=label if label is not None else r[1]
    cells=[mvpf(r[2])]+[num(x) for x in r[3:10]]
    return f"({code}) & {lab} & " + ' & '.join(cells) + r' \\' + '\n'

def panel(title):
    return r'\multicolumn{10}{@{}l}{\textit{' + title + r'}} \\' + '\n'

def write(name, src_note, body):
    with open(OUT+name,'w') as f:
        f.write(f"% Generated by gen_tables.py from FROT {src_note}.\n% Source numbers: May 2025 simulation of the estimated model (FROT 2025 submission). Do not edit numbers by hand.\n")
        f.write(body)

data={}
# ---------- claiming-age reforms
rows=parse('welfare_age_dependence_mvpfv5.tex')
data['claiming']=rows
lab={}
for r in rows:
    l=r[1].replace('\\%','\\%')
    l=l.replace('Linear $\\pm 7\\%$','Linear $\\pm$7\\%')
    lab[r[0]]=re.sub(r'\$\\pm\s*(\d+)\\%\$',r'$\\pm$\1\\%',l).replace('  ',' ').strip()
body=HEAD
body+=panel('A. Raising the normal retirement age (NRA)')
for r in rows:
    if r[0].startswith('AN'): body+=rowtex(r, lab[r[0]])
body+=r'\addlinespace'+'\n'+panel('B. Raising the delayed retirement credit (DRC)')
for r in rows:
    if r[0].startswith('AD'): body+=rowtex(r, lab[r[0]])
body+=r'\addlinespace'+'\n'+panel('C. Symmetric actuarial adjustment around the NRA')
for r in rows:
    if r[0].startswith('AL'): body+=rowtex(r, lab[r[0]])
body+=FOOT
write('tab_claiming_body.tex','tables/welfare_age_dependence_mvpfv5.tex',body)

# ---------- progressivity and level
rows=parse('welfare_progressivity_mvpfv7.tex')
data['generosity']=rows
def br(r):
    t=r[1].strip('() ').split(',')
    return '('+', '.join(x.strip() for x in t)+')'
body=HEAD.replace('& Reform &','& PIA rates &')
body+=panel('A. Raising the first PIA rate (bottom bracket)')
for r in rows:
    if r[0].startswith('P1'): body+=rowtex(r, br(r))
body+=r'\addlinespace'+'\n'+panel('B. Raising all PIA rates proportionally (level)')
for r in rows:
    if r[0].startswith('L'): body+=rowtex(r, br(r))
body+=FOOT
write('tab_generosity_body.tex','tables/welfare_progressivity_mvpfv7.tex (rows P1, L)',body)
body=HEAD.replace('& Reform &','& PIA rates &')
body+=panel('A. Raising the second PIA rate (first rate at 0.99)')
for r in rows:
    if r[0].startswith('P2'): body+=rowtex(r, br(r))
body+=r'\addlinespace'+'\n'+panel('B. Raising the third PIA rate (first two rates at 0.99 and 0.352)')
for r in rows:
    if r[0].startswith('P3'): body+=rowtex(r, br(r))
body+=FOOT
write('tab_generosity_app_body.tex','tables/welfare_progressivity_mvpfv7.tex (rows P2, P3)',body)

# ---------- other instruments
parts=[]
med=parse('welfare_medicare_mvpfv8.tex'); data['medicare']=med
tax=parse('welfare_tax_mvpf_v8.tex') if os.path.exists('../tables/welfare_tax_mvpf_v8.tex') else []
sav=parse('welfare_savings_mvpf_v3.tex') if os.path.exists('../tables/welfare_savings_mvpf_v3.tex') else []
data['tax']=tax; data['savings']=sav
body=HEAD
body+=panel('A. Medicare: coverage of medical expenditures after age 65 raised by 20 percentage points')
for r in med:
    nm={'Medicare Part A':('MA','Part A: all individuals'),'Medicare Part B':('MB','Part B: nonparticipants')}[r[0]]
    cells=[mvpf(r[2])]+[num(x) for x in r[3:10]]
    body+=f"({nm[0]}) & {nm[1]} & "+' & '.join(cells)+r' \\'+'\n'
body+=r'\addlinespace'+'\n'+panel('B. Old-age income tax: level parameter $\\lambda_t$ raised by $x(t-61)$ at ages $t\\geq 62$')
for i,r in enumerate(tax):
    body+=rowtex(r, f'$x={i+1}\\%$')
body+=r'\addlinespace'+'\n'+panel('C. Savings subsidy: net return on assets raised at all ages')
for r,lbl in zip(sav,['+0.2 pp','+0.4 pp','+0.8 pp']):
    body+=rowtex(r, lbl)
body+=FOOT
write('tab_other_body.tex','tables/welfare_medicare_mvpfv8.tex, welfare_tax_mvpf_v8.tex, welfare_savings_mvpf_v3.tex',body)
json.dump(data,open('tools/reform_data.json','w'),indent=1)
print({k:len(v) for k,v in data.items()})
